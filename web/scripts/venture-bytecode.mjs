import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

// Writes the QuiverToken creation bytecode the venture launch form mines its
// vanity salt against. Run after any QuiverToken change and before deploying:
//
//   cd contracts && npx hardhat compile && cd .. && node web/scripts/venture-bytecode.mjs
//
// A stale copy mines addresses the factory never produces, so every launch
// reverts on the vanity check.
const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(here, "..", "..");
const artifact = path.join(root, "contracts/artifacts/contracts/v4/QuiverToken.sol/QuiverToken.json");
const { bytecode } = JSON.parse(fs.readFileSync(artifact, "utf8"));
const out = path.join(root, "web/src/venture/tokenBytecode.ts");
fs.writeFileSync(out, `// QuiverToken creation bytecode for the venture launch form's vanity salt
// mining. Generated by web/scripts/venture-bytecode.mjs; do not edit by hand.
export const QUIVER_TOKEN_BYTECODE =
  "${bytecode}" as const;
`);
console.log(`wrote ${path.relative(root, out)} (${(bytecode.length - 2) / 2} bytes)`);
