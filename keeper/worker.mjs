// Cloudflare Worker that runs the venture ops keeper every minute (cron in
// wrangler.toml). The run is venture-ops-core.mjs, the same one the Node
// entry runs. A Durable Object holds a lease so a slow run is never joined by
// the next minute's (two runs at once would race each other's nonces and send
// the same fills and payouts twice), and remembers between runs what the last
// 24h of runs spent, which actions failed and are waiting to be retried, and
// the event history indexed so far (a run reads only the blocks since).
//
// A chain can carry several systems (a redeploy leaves the old coins on the
// old one); a run does each in turn under one spend cap. Each keeps its own
// index, retry list and buyback timers in storage under its own key: the
// oldest system under the keys a single system always used ("index:…",
// "backoff"), so it carries on where it was, the others under
// "index@<factory>:…", "backoff@<factory>" and "frenzy@<factory>".
import { DurableObject } from "cloudflare:workers";
import { checkDeployment, readConfig } from "./venture-config-core.mjs";
import { runOps } from "./venture-ops-core.mjs";
// Every system on the environment's chain, oldest first, bundled by
// wrangler.toml's build command (make-deployments.mjs).
import deps from "./deployments.gen.json";
// Generated by make-token-source.mjs: what every coin's code is compiled from.
import tokenSource from "./token-source.json";

// A run stops starting work at RUN_MS, and the lease outlasts it, so a run
// still going always holds the lease. A run killed mid-way (a redeploy does
// that) holds the next ones off until LEASE_MS at most.
const RUN_MS = 4 * 60_000;
const LEASE_MS = 5 * 60_000;
const DAY_MS = 86_400_000;

export class RunLock extends DurableObject {
  // A Durable Object handles one storage step at a time, so no other call
  // lands between the read and the write. Returns null while a run holds the
  // lease, else what the run needs to know about earlier ones.
  async acquire(now) {
    if (((await this.ctx.storage.get("until")) ?? 0) > now) return null;
    await this.ctx.storage.put("until", now + LEASE_MS);
    const spends = (await this.ctx.storage.get("spends")) ?? [];
    const spentTodayWei = spends.filter(([at]) => at > now - DAY_MS).reduce((t, [, wei]) => t + BigInt(wei), 0n);
    // The index is stored in parts (meta, one per coin, one per pool) so a run
    // rewrites only what it changed. Keyed by system ("" is the oldest).
    const index = {};
    for (const [k, v] of await this.ctx.storage.list({ prefix: "index" })) {
      const [head, kind, id] = k.split(":");
      const sys = head === "index" ? "" : head.slice("index@".length);
      const ix = (index[sys] ??= { meta: null, coins: {}, bands: {} });
      if (kind === "meta") ix.meta = v;
      else if (kind === "coin") ix.coins[id] = v;
      else if (kind === "bands") ix.bands[id] = v;
    }
    const keyed = async (prefix) => {
      const out = {};
      for (const [k, v] of await this.ctx.storage.list({ prefix })) out[k === prefix ? "" : k.slice(prefix.length + 1)] = v;
      return out;
    };
    return { spentTodayWei: spentTodayWei.toString(), backoff: await keyed("backoff"), frenzy: await keyed("frenzy"), index,
      sourcify: (await this.ctx.storage.get("sourcify")) ?? {}, feed: (await this.ctx.storage.get("feed")) ?? {} };
  }
  async release(now, spentWei, parts = {}, sourcify = {}, feed = {}) {
    const spends = ((await this.ctx.storage.get("spends")) ?? []).filter(([at]) => at > now - DAY_MS);
    if (BigInt(spentWei) > 0n) spends.push([now, spentWei]);
    await this.ctx.storage.put({ spends, sourcify, feed, ...parts });
    await this.ctx.storage.delete("until");
  }
}

export default {
  async scheduled(_event, env) {
    const lock = env.LOCK.get(env.LOCK.idFromName("venture-ops"));
    const held = await lock.acquire(Date.now());
    if (!held) {
      console.log("previous run still going; skipped");
      return;
    }
    const deadlineMs = Date.now() + RUN_MS;
    const spentToday = BigInt(held.spentTodayWei);
    let runSpent = 0n;
    const parts = {};
    let failure = null;
    try {
      const cfg = readConfig(env);
      // Secrets (wrangler secret put): each feed destination is off until set.
      const feed = { telegramToken: env.TELEGRAM_BOT_TOKEN, telegramChat: env.TELEGRAM_CHAT_ID, discordWebhook: env.DISCORD_WEBHOOK_URL };
      for (const [i, dep] of deps.entries()) {
        const sys = i === 0 ? "" : dep.contracts.factory.toLowerCase();
        const at = (name) => (sys ? `${name}@${sys}` : name);
        // Launch feed and Sourcify progress are per coin, so the systems share them.
        const memory = {
          spentTodayWei: spentToday + runSpent, runSpentWei: runSpent, deadlineMs,
          backoff: held.backoff[sys] ?? {}, frenzy: held.frenzy[sys] ?? {}, index: held.index[sys] ?? { meta: null, coins: {}, bands: {} },
          sourcify: held.sourcify, feed: held.feed,
        };
        try {
          const where = `bundled deployment ${dep.contracts.factory} (chain ${dep.chainId})`;
          checkDeployment(dep, cfg.CHAIN_ID, where);
          const s = await runOps({ cfg, dep, depPath: where, memory, tokenSource, feed });
          if (s.solvency.ok === false) failure ??= new Error(`CRITICAL ${dep.contracts.factory} insolvent: ${JSON.stringify(s.solvency)}`);
        } catch (e) {
          // One system failing must not stop the next.
          failure ??= e;
          console.log(`system ${dep.contracts.factory} failed: ${String(e?.message ?? e).slice(0, 200)}`);
        } finally {
          // Recorded even when the run threw: what it spent before failing counts.
          runSpent += memory.spentWei ?? 0n;
          for (const key of memory.indexDirty ?? []) {
            const [kind, id] = key.split(":");
            parts[`${at("index")}:${key}`] = kind === "meta" ? memory.index.meta : kind === "coin" ? memory.index.coins[id] : memory.index.bands[id];
          }
          parts[at("backoff")] = memory.backoff;
          parts[at("frenzy")] = memory.frenzy;
          held.sourcify = memory.sourcify;
          held.feed = memory.feed;
        }
      }
    } catch (e) {
      failure ??= e;
    } finally {
      await lock.release(Date.now(), String(runSpent), parts, held.sourcify, held.feed);
    }
    // Thrown so the run shows as failed in the Workers dashboard.
    if (failure) throw failure;
  },
};
